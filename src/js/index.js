/**
 * 获取根据计时偏移量矫正后的当前日期对象
 * @returns {Date} 矫正后的 Date 对象
 */
function getCurrentEditedDate() {
    let d = new Date();
    d.setSeconds(d.getSeconds() + timeOffset)
    return d;
}

/**
 * 返回本地日期的稳定存储键。
 * @param {Date} date 本地日期
 * @returns {string} YYYY-MM-DD 日期键
 */
function getLocalDateKey(date) {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
}

/**
 * 获取矫正后的当前星期索引（0-6）
 * 处理日期偏移逻辑，如果不是当天设置的偏移则重置
 * @param {Date} date - 当前日期对象
 * @returns {number} 星期索引
 */
function getCurrentEditedDay(date) {
    if (dayOffset === -1)
        return date.getDay();
    if (setDayOffsetDate === getLocalDateKey(date)) {
        return dayOffset;
    }
    localStorage.setItem('dayOffset', '-1')
    localStorage.setItem('setDayOffsetDate', '')
    dayOffset = -1
    setDayOffsetDate = ''
    return date.getDay();
}

